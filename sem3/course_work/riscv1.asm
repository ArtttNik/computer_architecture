.data
# Массивы указателей на строки с текстовыми представлениями чисел
units:      .word unit0, unit1, unit2, unit3, unit4, unit5, unit6, unit7, unit8, unit9
tens:       .word ten0, ten1, ten2, ten3, ten4, ten5, ten6, ten7, ten8, ten9
hundreds:   .word hundred0, hundred1, hundred2

# Текстовые представления единиц (0-9)
unit0:      .asciz ""           # пустая строка для 0
unit1:      .asciz "один"
unit2:      .asciz "два"
unit3:      .asciz "три"
unit4:      .asciz "четыре"
unit5:      .asciz "пять"
unit6:      .asciz "шесть"
unit7:      .asciz "семь"
unit8:      .asciz "восемь"
unit9:      .asciz "девять"

# Текстовые представления десятков (0-90)
ten0:       .asciz ""           # пустая строка для 0
ten1:       .asciz "десять"
ten2:       .asciz "двадцать"
ten3:       .asciz "тридцать"
ten4:       .asciz "сорок"
ten5:       .asciz "пятьдесят"
ten6:       .asciz "шестьдесят"
ten7:       .asciz "семьдесят"
ten8:       .asciz "восемьдесят"
ten9:       .asciz "девяносто"

# Текстовые представления сотен (0-200)
hundred0:   .asciz ""           # пустая строка для 0
hundred1:   .asciz "сто"
hundred2:   .asciz "двести"

# Особые случаи: числа 10-19
special10:  .asciz "десять"
special11:  .asciz "одиннадцать"
special12:  .asciz "двенадцать"
special13:  .asciz "тринадцать"
special14:  .asciz "четырнадцать"
special15:  .asciz "пятнадцать"
special16:  .asciz "шестнадцать"
special17:  .asciz "семнадцать"
special18:  .asciz "восемнадцать"
special19:  .asciz "девятнадцать"

# Массив указателей на особые случаи (10-19)
special:    .word special10, special11, special12, special13, special14, special15, special16, special17, special18, special19

# Константы и строки для ввода/вывода
max_value:  .word 255           # максимальное допустимое значение
space:      .asciz " "          # строка пробела для разделения слов
newline:    .asciz "\n"         # строка перевода строки
prompt:     .asciz "Введите число от 0 до 255: "  # приглашение для ввода
zero_text:  .asciz "ноль"       # текстовое представление нуля
error_msg:  .asciz "Ошибка: число должно быть от 0 до 255!\n"  # сообщение об ошибке

.text

# -----------------------
# Определения макросов
# -----------------------

# InputModule: вывести prompt, прочитать int -> s0, проверить диапазон
.macro InputModule
    la a0, prompt              # загрузить адрес строки приглашения в a0
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов

    li a7, 5                   # системный вызов для чтения целого числа
    ecall                      # выполнить системный вызов
    mv s0, a0                  # сохранить введенное число в s0

    blt s0, x0, input_error    # если число < 0, перейти к ошибке
    lw t0, max_value           # загрузить максимальное значение (255) в t0
    bgt s0, t0, input_error    # если число > 255, перейти к ошибке
.end_macro

# HundredsModule: печать сотен (s1), затем пробел (если s1 != 0)
.macro HundredsModule
    beqz s1, .HundredsDone     # если сотен нет (s1 = 0), пропустить печать
    la t0, hundreds            # загрузить адрес массива сотен
    slli t1, s1, 2             # умножить номер сотен на 4 (размер слова)
    add t0, t0, t1             # вычислить адрес элемента массива
    lw a0, 0(t0)               # загрузить адрес строки с текстом сотен
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов

    la a0, space               # загрузить адрес строки с пробелом
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
.HundredsDone:
.end_macro

# TensModule: если s3==1 -> handle_special_case (10..19),
# иначе печать десятков (если s3 != 0) и пробел
.macro TensModule
    li t0, 1                   # загрузить значение 1 для сравнения
    beq s3, t0, handle_special_case  # если десятки = 1, обработать особый случай (10-19)
    beqz s3, .TensDone         # если десяток нет (s3 = 0), пропустить печать

    la t0, tens                # загрузить адрес массива десятков
    slli t1, s3, 2             # умножить номер десятков на 4 (размер слова)
    add t0, t0, t1             # вычислить адрес элемента массива
    lw a0, 0(t0)               # загрузить адрес строки с текстом десятков
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов

    la a0, space               # загрузить адрес строки с пробелом
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
.TensDone:
.end_macro

# UnitsModule: печать единиц (s4) если s4 != 0
.macro UnitsModule
    beqz s4, .UnitsDone        # если единиц нет (s4 = 0), пропустить печать
    la t0, units               # загрузить адрес массива единиц
    slli t1, s4, 2             # умножить номер единиц на 4 (размер слова)
    add t0, t0, t1             # вычислить адрес элемента массива
    lw a0, 0(t0)               # загрузить адрес строки с текстом единиц
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
.UnitsDone:
.end_macro

# SpecialModule: печать 10..19 по таблице special (индексируется s4)
.macro SpecialModule
    la t0, special             # загрузить адрес массива особых случаев
    slli t1, s4, 2             # умножить номер на 4 (размер слова)
    add t0, t0, t1             # вычислить адрес элемента массива
    lw a0, 0(t0)               # загрузить адрес строки с текстом числа 10-19
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
.end_macro

# EndModule: перевод строки + exit
.macro EndModule
    la a0, newline             # загрузить адрес строки с переводом строки
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов

    li a7, 10                  # системный вызов для завершения программы
    ecall                      # выполнить системный вызов
.end_macro

# -----------------------
# Основная программа
# -----------------------
main:
    InputModule                # ввод и проверка (записывает s0)

    beqz s0, print_zero        # если введен 0 -> печатаем "ноль" и завершаем

    # Разбиение числа на разряды
    li t0, 100                 # загрузить делитель 100
    div s1, s0, t0             # s1 = сотни (s0 / 100)
    rem s2, s0, t0             # s2 = остаток после сотен (s0 % 100)

    li t0, 10                  # загрузить делитель 10
    div s3, s2, t0             # s3 = десятки (s2 / 10)
    rem s4, s2, t0             # s4 = единицы (s2 % 10)

    # Последовательная обработка разрядов
    HundredsModule             # обработка сотен
    # продолжение — обработка десятков/единиц
    TensModule                 # обработка десятков
    UnitsModule                # обработка единиц
    j end_program              # переход к завершению программы

# Обработка особых случаев (числа 10-19)
handle_special_case:
    SpecialModule              # печать числа 10-19
    j end_program              # переход к завершению программы

# Печать нуля
print_zero:
    la a0, zero_text           # загрузить адрес строки "ноль"
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
    j end_program              # переход к завершению программы

# Обработка ошибки ввода
input_error:
    la a0, error_msg           # загрузить адрес сообщения об ошибке
    li a7, 4                   # системный вызов для печати строки
    ecall                      # выполнить системный вызов
    j main                     # вернуться к началу программы для повторного ввода

# Место завершения программы
end_program:
    EndModule                  # завершение программы (перевод строки + exit)